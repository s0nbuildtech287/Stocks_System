/**
 * Generate high-fidelity 52-week (1-year) long term trend series for a stock
 */
export function getStockLongTermTrend(stock: StockProfile, pointsCount: number = 40): number[] {
  if (stock.sparklineLong && stock.sparklineLong.length >= pointsCount) {
    return stock.sparklineLong;
  }
  const low = stock.low52w;
  const high = stock.high52w;
  const cur = stock.price;

  // Determine realistic starting price 52 weeks ago based on profitGrowth and beta
  const trendStrength = (stock.profitGrowthYoY > 0 ? 0.35 : -0.15) + (stock.roe > 18 ? 0.2 : 0.0);
  const startRatio = Math.max(0.7, Math.min(1.25, 1 - trendStrength * 0.4));
  let startPrice = cur * startRatio;
  startPrice = Math.max(low * 1.02, Math.min(high * 0.98, startPrice));

  const points: number[] = [startPrice];
  const step = (cur - startPrice) / pointsCount;

  // Deterministic seed based on ticker characters
  const seed = stock.ticker.split("").reduce((acc, c) => acc + c.charCodeAt(0), 0);

  for (let i = 1; i < pointsCount - 1; i++) {
    const progress = i / pointsCount;
    // Base trajectory linear interpolation + sinusoidal market cycles
    const base = startPrice + step * i;
    const cycle1 = Math.sin((progress * Math.PI * 2.5) + (seed % 7)) * ((high - low) * 0.22);
    const cycle2 = Math.cos((progress * Math.PI * 4) + (seed % 5)) * ((high - low) * 0.12);
    
    let p = base + cycle1 + cycle2;
    p = Math.max(low, Math.min(high, p));
    points.push(Math.round(p));
  }

  // Ensure last point is exactly current price
  points.push(cur);
  return points;
}

